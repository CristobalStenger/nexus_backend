-- BOLETA 1 --- N DETALLE_BOLETA
-- usuario_id y producto_id apuntan a tablas de otros microservicios (otros schemas),
-- por eso no tienen FOREIGN KEY: la relación es lógica. La boleta guarda una copia
-- de los datos del cliente y de cada producto tal como estaban al momento de comprar.
CREATE TABLE boleta (
    numero               BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    fecha                TIMESTAMPTZ  NOT NULL DEFAULT now(),
    estado               VARCHAR(10)  NOT NULL CHECK (estado IN ('pagada', 'rechazada')),
    motivo               VARCHAR(500) NOT NULL DEFAULT '',
    usuario_id           BIGINT,               -- null: compra sin iniciar sesión
    cliente_run          VARCHAR(9)   NOT NULL DEFAULT '',
    cliente_nombre       VARCHAR(50)  NOT NULL,
    cliente_apellidos    VARCHAR(100) NOT NULL,
    cliente_correo       VARCHAR(100) NOT NULL,
    entrega_tipo         VARCHAR(10)  NOT NULL CHECK (entrega_tipo IN ('despacho', 'retiro')),
    entrega_calle        VARCHAR(300) NOT NULL,
    entrega_departamento VARCHAR(50)  NOT NULL DEFAULT '',
    entrega_region       VARCHAR(100) NOT NULL,
    entrega_comuna       VARCHAR(100) NOT NULL,
    entrega_indicaciones VARCHAR(300) NOT NULL DEFAULT '',
    pago_tarjeta         VARCHAR(20)  NOT NULL, -- solo los últimos 4 dígitos: **** 4242
    cupon_codigo         VARCHAR(30),
    cupon_descuento      INTEGER,
    subtotal             INTEGER      NOT NULL CHECK (subtotal >= 0),
    descuento            INTEGER      NOT NULL CHECK (descuento >= 0),
    envio                INTEGER      NOT NULL CHECK (envio >= 0),
    total                INTEGER      NOT NULL CHECK (total >= 0)
);

CREATE TABLE detalle_boleta (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boleta_numero BIGINT       NOT NULL REFERENCES boleta (numero) ON DELETE CASCADE,
    producto_id   BIGINT       NOT NULL,
    codigo        VARCHAR(30)  NOT NULL,
    nombre        VARCHAR(100) NOT NULL,
    categoria     VARCHAR(50)  NOT NULL,
    imagen        VARCHAR(500) NOT NULL DEFAULT '',
    precio        INTEGER      NOT NULL CHECK (precio >= 0), -- unitario, con el descuento del producto
    cantidad      INTEGER      NOT NULL CHECK (cantidad > 0)
);

CREATE INDEX idx_detalle_boleta_numero ON detalle_boleta (boleta_numero);
CREATE INDEX idx_boleta_usuario ON boleta (usuario_id);
